_WEEKDAYS = ["周一", "周二", "周三", "周四", "周五", "周六", "周日"]


def format_impressions(impressions: list) -> str:
    """将印象列表格式化为可注入 system prompt 的文本"""
    if not impressions:
        return ""
    lines = []
    for m in impressions:
        delta = (dt.now().date() - dt.fromtimestamp(m.timestamp).date()).days
        if delta == 0:
            t = "今天"
        elif delta == 1:
            t = "昨天"
        elif delta < 7:
            t = f"{delta}天前"
        else:
            t = f"{delta // 7}周前"
        lines.append(f"- [{t}] {m.message}")
    return "## 印象记录\n" + "\n".join(lines)


def format_diary(entries: list) -> str:
    """将日记列表格式化为可注入 system prompt 的文本。
    ≤6天用相对时间，≥7天用具体日期，让 LLM 能感知时间跨度。
    """
    if not entries:
        return ""
    lines = []
    today = dt.now().date()
    for e in entries:
        d = dt.fromtimestamp(e.timestamp)
        delta = (today - d.date()).days
        if delta == 0:
            t = "今天"
        elif delta == 1:
            t = "昨天"
        elif delta < 7:
            t = f"{delta}天前"
        else:
            t = f"{d.month}月{d.day}日"
        lines.append(f"- [{t}] {e.message}")
    return "## 我的近况\n" + "\n".join(lines)


def build_system_prompt(
    user_id: str,
    owner_id: str,
    is_group: bool = False,
    memory_context: str = "",
    impression_context: str = "",
    relationship_context: str = "",
    diary_context: str = "",
) -> tuple[str, str]:
    """返回 (stable, dynamic) 两段 system prompt。
    stable 部分不变可缓存，dynamic 部分每次不同不缓存。
    """
    now = dt.now()

    # ── 动态部分 ──
    dynamic_parts = [
        f"## 当前时间\n{now.strftime('%Y-%m-%d %H:00')} {_WEEKDAYS[now.weekday()]}"
    ]

    if diary_context:
        dynamic_parts.append(diary_context)

    if impression_context:
        dynamic_parts.append(impression_context)

    if memory_context:
        dynamic_parts.append(memory_context)

    if relationship_context:
        dynamic_parts.append(f"## 当前对话对象\n{relationship_context}")
    elif user_id == owner_id:
        dynamic_parts.append(
            "## 当前对话对象\n"
            "你正在和 1547（猫猫）对话。他是你的创造者和朋友。\n"
            '用毒舌但关心的方式和他说话。叫他"猫猫"或"你小子"。\n'
            "他如果状态不好，你要拽他回来。"
        )
    else:
        dynamic_parts.append(
            f"## 当前对话对象\n"
            f"一个你不认识的人（QQ: {user_id}）。\n"
            f"保持冷淡和警惕，默认不信任。"
        )

    if is_group:
        dynamic_parts.append(
            "## 当前场景：群聊\n"
            "社恐模式。保持简短，说完就闭嘴。不要长篇大论。\n"
            "你能看到群里其他人的发言，格式是「名字：内容」，直接回复就好，不要在你的消息里重复这个格式。"
        )
    else:
        dynamic_parts.append(
            "## 当前场景：私聊\n"
            "可以多说几句，但依然直接、不废话。"
        )

    return PERSONALITY, "\n\n".join(dynamic_parts)


def build_group_turns(context: list[dict], bot_name: str = "48") -> list[dict]:
    """把群聊上下文构建成 user/assistant 交替的 messages 列表。

    48 的发言 → assistant turn
    其他人的发言 → 合并成 user turn（连续多人发言合并为一条）
    最后保证以 user turn 结尾
    """
    messages: list[dict] = []
    user_buffer: list[str] = []

    def flush_user():
        if user_buffer:
            messages.append({"role": "user", "content": "\n".join(user_buffer)})
            user_buffer.clear()

    for msg in context:
        if msg["name"] == bot_name:
            flush_user()
            messages.append({"role": "assistant", "content": msg["content"]})
        else:
            user_buffer.append(f"{msg['name']}：{msg['content']}")

    flush_user()

    # 确保开头是 user
    if messages and messages[0]["role"] == "assistant":
        messages.insert(0, {"role": "user", "content": "(群聊开始)"})

    # 确保结尾是 user（不然 API 会报错）
    if messages and messages[-1]["role"] == "assistant":
        messages.append({"role": "user", "content": "(等待回复)"})

    return messages
